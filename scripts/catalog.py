#!/usr/bin/env python3
"""Render an overview from the metadata snapshot without touching the server."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
d = json.loads((root / "inventory/observed.json").read_text())
lines = ["# Observed services", "", "Generated by `python3 scripts/catalog.py` from `inventory/observed.json`.",
         "Installed definitions and stopped containers are included; this snapshot is not a health check.",
         "", "Observed at " + d["observed_at"] + ".", "",
         "## Compose projects", "", "| Project | Directory | Containers |", "| --- | --- | --- |"]
for name, p in sorted(d["compose_projects"].items()):
    containers = [c["name"] for c in d["containers"] if c["compose_project"] == name]
    lines.append(f"| {name} | `{p['directory']}` | {', '.join(containers)} |")
lines += ["", "## Standalone containers", "", "| Container | Image | State |", "| --- | --- | --- |"]
for c in d["containers"]:
    if not c["compose_project"]:
        lines.append(f"| {c['name']} | `{c['image']}` | {c['state']} |")
lines += ["", "## Launchd definitions", "", "| Label | Domain | Executable | Schedule |", "| --- | --- | --- | --- |"]
for a in d["launch_agents"]:
    schedule = str(a["calendar"]) if a["calendar"] else (f"every {a['interval_seconds']}s" if a["interval_seconds"] else ("keep alive" if a["keep_alive"] else "at load"))
    lines.append(f"| {a['label']} | {a.get('scope', 'user')} | `{a['executable']}` | {schedule} |")
lines += ["", "## Tunnel routes", "", "| Hostname | Local destination | Config |", "| --- | --- | --- |"]
for r in d.get("ingress_routes", []):
    lines.append(f"| {r['hostname']} | `{r['service']}` | `{r['config']}` |")
lines += ["", "See [operations](operations.md) for ownership mismatches and [migration](migration.md) before moving data.", ""]
(root / "docs/services.md").write_text("\n".join(lines))
